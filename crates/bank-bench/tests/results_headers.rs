//! **A committed CSV must carry the header the code writes today.**
//!
//! `results_manifest.rs` checks that every file under `results/` is *listed*. Nothing checked
//! what is *in* one. So when T-02 (cycle 7) added `fallback_rate` to `SCALING_CSV_HEADER`,
//! the constant, the renderer and the parser all moved together and the two committed E19
//! CSVs — machine-dependent, regenerated only by a `--publish` run on the reference host —
//! kept the header they were published with. A reader comparing an E19 column against a
//! current run was comparing two different schemas, and the workspace was green.
//!
//! This is the general shape of the defect and not one instance of it: a machine-dependent
//! artefact cannot be regenerated by `make reproduce` *by construction*, so the only thing
//! that can notice its schema drifting is a test that reads it.
//!
//! **What a failure here means.** Not that the code is wrong — the constant is the current
//! truth. It means the committed artefact predates it and must be re-measured on the host it
//! belongs to, or marked `not_run` with the reason. Deleting the row, or hand-editing the
//! header onto stale data, would be fabricating a measurement.

use std::path::{Path, PathBuf};

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// **Every machine-dependent results file states the checkpoint interval it ran at.**
///
/// `MISMATCH-daemon-checkpoints` is what this exists for. The daemon behind every wall-clock
/// figure in this repository ran with `checkpoint_interval = 0` — the configuration §9.4.1
/// says the cost law excludes — and no artefact said so, for four cycles, because C was not
/// a flag and therefore not a thing a header could carry. Cycle 13 made it a flag
/// (`--nls-checkpoint`) and made saying so a rule.
///
/// The rule applies to `machine-dependent` files, which is where it matters: those are the
/// ones `make reproduce` never regenerates, so nothing else can notice that the
/// configuration behind them is unstated. `historical` rows are exempt by definition — they
/// record a configuration that no longer exists — and byte-deterministic files are covered
/// by `every_regenerable_csv_carries_its_configuration`.
#[test]
fn every_machine_dependent_results_file_states_its_checkpoint_interval() {
    let root = repo_root();
    let manifest =
        std::fs::read_to_string(root.join("results/MANIFEST.csv")).expect("MANIFEST.csv");
    let mut silent = Vec::new();
    for line in manifest.lines() {
        if line.starts_with('#') || line.trim().is_empty() {
            continue;
        }
        let mut it = line.splitn(3, ',');
        let (Some(path), Some(class)) = (it.next(), it.next()) else {
            continue;
        };
        if class.trim() != "machine-dependent" {
            continue;
        }
        let text = match std::fs::read_to_string(root.join("results").join(path.trim())) {
            Ok(t) => t,
            Err(_) => continue, // `results_manifest.rs` owns "is it on disk"
        };
        // Either the artefact states it, or `MANIFEST.csv`'s checkpoint block does.
        //
        // The second is not a loophole, it is the honest form for data taken before the
        // flag existed: a configuration line written onto such a file would be
        // indistinguishable from a measured column, and this project's rule is that a
        // header is not edited onto data taken without it. The manifest says C and says how
        // it is known, in one place, where a reader comparing two artefacts will see both.
        let stated_in_file = text.contains("checkpoint_interval")
            || text.contains("checkpoint interval")
            || text.contains("`--nls-checkpoint`");
        let stated_in_manifest = manifest
            .lines()
            .filter(|l| l.trim_start().starts_with("#   C="))
            .any(|l| l.split_whitespace().any(|w| w == path.trim()));
        if !stated_in_file && !stated_in_manifest {
            silent.push(path.trim().to_string());
        }
    }
    assert!(
        silent.is_empty(),
        "these machine-dependent results say nothing about the checkpoint interval they were \
         measured at: {silent:?}\n\
         C is `--nls-checkpoint` on `bench` and `checkpoint_interval` in the experiments' \
         configuration line. A wall-clock figure whose bounding mechanism is unstated is the \
         defect `MISMATCH-daemon-checkpoints` records; state it, do not delete this test."
    );
}

/// Every `.csv` under `results/`, and the constant its header must equal.
///
/// `None` means "written by something outside this crate" — the experiments binary, the
/// memory probe, the compiled sweep — and those files are regenerated by `make reproduce`,
/// which diffs them, so a drift there is caught already. The table is exhaustive on purpose:
/// a new CSV that nobody classified fails `every_committed_csv_is_classified` rather than
/// being silently unchecked, which is how `E19-scaling/point.csv` went a cycle unnoticed.
fn expected(path: &str) -> Option<Option<&'static str>> {
    use bank_bench::render::CSV_HEADER;
    use bank_bench::workloads::{MIXED_CSV_HEADER, SCALING_CSV_HEADER};
    Some(match path {
        "E16-wallclock/oltp.csv"
        | "E16-wallclock/analytical.csv"
        | "E16-wallclock/analytical-statements.csv"
        | "E16-wallclock/point.csv"
        | "E16-wallclock/durable.csv"
        | "E16-wallclock/report.csv" => Some(CSV_HEADER),
        // `fold` joined the scaling experiment in cycle 13: it is the scan-heavy arm, and
        // the one whose flatness above four connections is the host rather than the lock.
        "E19-scaling/point.csv" | "E19-scaling/durable.csv" | "E19-scaling/fold.csv" => {
            Some(SCALING_CSV_HEADER)
        }
        "E19-scaling/mixed.csv" => Some(MIXED_CSV_HEADER),
        // The device ceiling: written inline by `bench`, four figures and a count.
        "E16-wallclock/device.csv" => Some("median,mad,lowest,highest,probes"),
        // Written outside this crate, and regenerated (and therefore diffed) by
        // `make reproduce`.
        "E23-scaling/E23-scaling.csv"
        | "E18-memory.csv"
        // The portable half of E18: allocation counts only, which any host must reproduce
        // exactly. The byte columns stay in `E18-memory.csv`, which carries the host that
        // produced them and is excluded from `make reproduce`'s diff — a byte total includes
        // the standard library's own per-platform type sizes and is not a property of this
        // code (proved on Host C: identical counts, byte totals apart by exactly the size
        // difference of `Completion`).
        | "E18-counts.csv"
        | "e1_correctness.csv"
        | "e2_duality.csv"
        | "e3_memory_vs_skew.csv"
        | "e4_phase.csv"
        | "e5_history.csv"
        | "e6_policies.csv"
        | "e7_write_path.csv"
        | "e8_rungs.csv"
        | "e9_history_refined.csv"
        | "e10_checkpoints.csv"
        | "e11_checkpoint_bound.csv"
        | "e12_phase_compiled.csv"
        | "E26-compile-cost.csv"
        | "obligations.csv"
        | "MANIFEST.csv" => None,
        _ => return None,
    })
}

fn committed_csvs() -> Vec<String> {
    let root = repo_root().join("results");
    let mut out = Vec::new();
    let mut stack = vec![root.clone()];
    while let Some(dir) = stack.pop() {
        let Ok(rd) = std::fs::read_dir(&dir) else {
            continue;
        };
        for e in rd.flatten() {
            let p = e.path();
            if p.is_dir() {
                stack.push(p);
            } else if p.extension().is_some_and(|x| x == "csv") {
                out.push(
                    p.strip_prefix(&root)
                        .expect("under results/")
                        .to_string_lossy()
                        .replace('\\', "/"),
                );
            }
        }
    }
    out.sort();
    out
}

#[test]
fn every_committed_csv_is_classified() {
    let unknown: Vec<String> = committed_csvs()
        .into_iter()
        .filter(|p| expected(p).is_none())
        .collect();
    assert!(
        unknown.is_empty(),
        "these CSVs are committed and nothing says what header they must carry: {unknown:?}\n\
         add each to `expected()` — either with the constant that writes it, or as `None` if \
         it is written outside this crate and regenerated by `make reproduce`"
    );
}

#[test]
fn every_committed_csv_carries_the_header_its_writer_writes_today() {
    let mut stale = Vec::new();
    for p in committed_csvs() {
        let Some(Some(want)) = expected(&p) else {
            continue;
        };
        let path = repo_root().join("results").join(&p);
        let text = std::fs::read_to_string(&path).expect("a committed CSV");
        // The column names, not the provenance comment above them. Cycle 13 put a
        // `# provenance:`/`# configuration:` block at the top of every counted-work CSV, and
        // a reader that takes the first line as the header would compare a comment against a
        // schema. Every reader of these files skips `#` first.
        let have = text
            .lines()
            .find(|l| !l.starts_with('#'))
            .unwrap_or("")
            .trim_end();
        if have != want {
            let missing: Vec<&str> = want
                .split(',')
                .filter(|c| !have.split(',').any(|h| h == *c))
                .collect();
            stale.push(format!(
                "\n  {p}\n    committed: {have}\n    writes now: {want}\n    columns the file \
                 does not have: {missing:?}"
            ));
        }
    }
    assert!(
        stale.is_empty(),
        "{} committed CSV(s) carry a header their writer no longer writes. The code is not \
         wrong: the artefact predates it, and every column comparison against it is between \
         two schemas. Re-measure on the host it belongs to, or mark its rows `not_run` with \
         the reason — never hand-edit a header onto data that was measured without it.{}",
        stale.len(),
        stale.join("")
    );
}

/// **Every regenerable results file says what produced it and under what configuration.**
///
/// The header is not decoration. Three findings in one cycle came from an artefact that did
/// not carry its own configuration: `e7_write_path.csv` was classed byte-deterministic for
/// eleven cycles while timing with `Instant`; section 9.13.2 says "20,000 reads" beside a
/// table the sweep produced at 40,000; and E8's rungs and E10's checkpoints were compared as
/// one claim while running at opposite `checkpoint_interval`s, which no file recorded.
///
/// **Why a configuration and not a commit, a host and a date.** A `byte-deterministic` file
/// is one any host reproduces with the pinned toolchain, and `make reproduce` proves it by
/// diffing. A date in it fails that diff on the second day and a hostname on the second
/// machine, so the file would stop being the thing its class says it is. Its provenance is
/// therefore exactly its configuration — the numbers are a pure function of that and the
/// committed code. Machine-dependent artefacts are the opposite case and carry the full
/// block: `bank_bench::render::Provenance` gathers host, instance, session, granted cores and
/// the commit `build.rs` stamps.
///
/// **What this does not yet cover, named so the gap is not silent.** The markdown documents
/// (a `#` line is a heading there, not a comment), `tools/memprobe`'s E18 files, and the
/// machine-dependent documents E16/E19/E23, whose headers require a re-measure on a named
/// host rather than a text edit — `MISMATCH-e16-header`, and cycle 13's E-2.
#[test]
fn every_regenerable_csv_carries_its_configuration() {
    let root = repo_root();
    let manifest = std::fs::read_to_string(root.join("results/MANIFEST.csv")).expect("readable");

    let mut missing = Vec::new();
    for line in manifest.lines() {
        if line.starts_with('#') || !line.contains(',') {
            continue;
        }
        let mut f = line.split(',');
        let (Some(path), Some(class)) = (f.next(), f.next()) else {
            continue;
        };
        // Historical files are not regenerable by definition; machine-dependent ones are the
        // E-2 gap above; only CSVs are covered, because `#` is a heading in markdown.
        if class != "byte-deterministic" && class != "toolchain-scoped" {
            continue;
        }
        if !path.ends_with(".csv") || path == "MANIFEST.csv" {
            continue;
        }
        // Written by a test rather than a harness, and its configuration is the corpus the
        // test walks; it is listed here so the exemption is visible rather than implicit.
        if path == "obligations.csv" {
            continue;
        }
        let text = match std::fs::read_to_string(root.join("results").join(path)) {
            Ok(t) => t,
            Err(_) => continue,
        };
        let head: Vec<&str> = text.lines().take(2).collect();
        let ok = head.first().is_some_and(|l| l.starts_with("# provenance:"))
            && head
                .get(1)
                .is_some_and(|l| l.starts_with("# configuration:"));
        if !ok {
            missing.push(path.to_string());
        }
    }
    assert!(
        missing.is_empty(),
        "these regenerable results files carry no provenance header: {missing:?}\n\
         Each must begin with `# provenance: <the command>` and `# configuration: <the \
         parameters>`, emitted by the producer from the bindings it runs with. Not \
         transcribed beside them: a transcribed configuration is a second copy of a fact, \
         and every defect this test exists for was a second copy going stale."
    );
}
