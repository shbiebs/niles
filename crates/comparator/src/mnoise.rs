//! **M-NOISE** (cycle 17, C17-04): why the refusal rule refuses. The design is
//! `docs/study/M-NOISE-design.md`, committed before any run.
//!
//! One cell (single, 10⁴, P+ against P-inc, q1 p50 and p99 at 1, 2 and 4 clients, five seeds)
//! at two run lengths. Each (length, seed, metric) is judged by [`crate::stats::judge`], the
//! function E27b's cells use; the verdict is the design's §5 rule, applied to the counts.

use crate::render::{diverged, series_of};
use crate::stats::{judge, Verdict};
use crate::store::Stored;
use bank_bench::score::{mad, median};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

pub const SEEDS: [u64; 5] = [1, 7, 42, 100, 2024];
pub const METRICS: [&str; 6] = [
    "q1_p50_us",
    "q1_p99_us",
    "c2_q1_p50_us",
    "c2_q1_p99_us",
    "c4_q1_p50_us",
    "c4_q1_p99_us",
];
const A: &str = "P+";
const B: &str = "P-inc";

/// One length's judged cells: (seed, metric) → verdict. A missing point is a refusal of every
/// cell it would have held, with that reason.
pub fn judged(dir: &Path) -> BTreeMap<(u64, &'static str), Verdict> {
    let mut out = BTreeMap::new();
    for seed in SEEDS {
        let path = dir.join(format!("single-10000-{seed}.tsv"));
        let st = Stored::read(&path);
        for m in METRICS {
            let v = match &st {
                Err(e) => Verdict::Refused(format!("no point ({e})")),
                Ok(st) => {
                    judge(
                        m,
                        A,
                        B,
                        &series_of(st, A, m),
                        &series_of(st, B, m),
                        (diverged(st, A), diverged(st, B)),
                        10_000,
                        seed,
                    )
                    .verdict
                }
            };
            out.insert((seed, m), v);
        }
    }
    out
}

/// The design's §5 rule. `r1` and `r2` are refused cells out of 30.
pub fn rule(r1: usize, r2: usize) -> &'static str {
    if r1 == 0 {
        "inconclusive: E27b's length refused nothing at this cell, so there is nothing to explain, and no later design changes because of M-NOISE"
    } else if 2 * r2 <= r1 {
        "run length is the cause: every later design on this host uses L2's lengths (2×)"
    } else {
        "the host is the cause: comparisons at 10⁵ and above move to the Mac (D17-7), and this host keeps 10³–10⁴"
    }
}

fn refused(v: &Verdict) -> bool {
    matches!(v, Verdict::Refused(_))
}

/// Each arm's warm-up MAD as a share of its warm-up median, per metric and seed.
fn warm_ratio(dir: &Path, seed: u64, arm: &str, metric: &str) -> Option<f64> {
    let st = Stored::read(&dir.join(format!("single-10000-{seed}.tsv"))).ok()?;
    let w: Vec<f64> = series_of(&st, arm, metric)
        .1
        .into_iter()
        .collect::<Option<_>>()?;
    let m = median(&w);
    (!w.is_empty() && m != 0.0).then(|| mad(&w) / m.abs())
}

pub fn render(l1: &Path, l2: &Path) -> String {
    let (j1, j2) = (judged(l1), judged(l2));
    let count = |j: &BTreeMap<(u64, &str), Verdict>| j.values().filter(|v| refused(v)).count();
    let (r1, r2) = (count(&j1), count(&j2));
    let mut s = String::new();
    let _ = writeln!(s, "# M-NOISE — why the refusal rule refuses (C17-04)\n");
    let _ = writeln!(s, "**Generated by `comparator m-noise` from `results/M-NOISE/L1` and `results/M-NOISE/L2`. Do not edit.** The design is `docs/study/M-NOISE-design.md`, committed before any run. One cell: single currency, 10⁴ accounts, P+ against P-inc, q1 p50 and p99 at 1, 2 and 4 clients, seeds 1, 7, 42, 100 and 2024; each (seed, metric) judged by `stats::judge`, as E27b's cells are. **L1** is E27b's length (200 operations and 60 reads per client per run, 3 warm-up runs); **L2** doubles both and the warm-up runs (400, 120, 6). Both have 10 measured runs.\n");
    let _ = writeln!(s, "## Verdict\n");
    let _ = writeln!(s, "| length | refused cells (of 30) |\n|---|--:|\n| L1 (E27b's) | {r1} |\n| L2 (2×, 2× warm-up) | {r2} |\n");
    let _ = writeln!(
        s,
        "**By the pre-registered rule (design §5): {}.**\n",
        rule(r1, r2)
    );
    let _ = writeln!(s, "## Refusals by reason\n");
    let _ = writeln!(s, "| length | reason | cells |\n|---|---|--:|");
    for (name, j) in [("L1", &j1), ("L2", &j2)] {
        let mut by: BTreeMap<String, usize> = BTreeMap::new();
        for v in j.values() {
            if let Verdict::Refused(why) = v {
                *by.entry(why.clone()).or_default() += 1;
            }
        }
        if by.is_empty() {
            let _ = writeln!(s, "| {name} | none | 0 |");
        }
        for (why, n) in by {
            let _ = writeln!(s, "| {name} | {why} | {n} |");
        }
    }
    let _ = writeln!(s, "\n## Every cell\n");
    let _ = writeln!(s, "| metric | seed | L1 | L2 |\n|---|--:|---|---|");
    for m in METRICS {
        for seed in SEEDS {
            let _ = writeln!(
                s,
                "| {m} | {seed} | {} | {} |",
                j1[&(seed, m)].word(),
                j2[&(seed, m)].word()
            );
        }
    }
    let _ = writeln!(
        s,
        "\n## Warm-up MAD as a share of the warm-up median (descriptive)\n"
    );
    let _ = writeln!(s, "The refusal threshold is 0.150. One row per metric and seed; `—` where a point or a metric is missing.\n");
    let _ = writeln!(
        s,
        "| metric | seed | P+ L1 | P+ L2 | P-inc L1 | P-inc L2 |\n|---|--:|--:|--:|--:|--:|"
    );
    let f = |x: Option<f64>| x.map(|v| format!("{v:.3}")).unwrap_or_else(|| "—".into());
    for m in METRICS {
        for seed in SEEDS {
            let _ = writeln!(
                s,
                "| {m} | {seed} | {} | {} | {} | {} |",
                f(warm_ratio(l1, seed, A, m)),
                f(warm_ratio(l2, seed, A, m)),
                f(warm_ratio(l1, seed, B, m)),
                f(warm_ratio(l2, seed, B, m))
            );
        }
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_rule_is_the_designs() {
        assert!(rule(0, 0).starts_with("inconclusive"));
        assert!(rule(0, 5).starts_with("inconclusive"));
        assert!(rule(10, 5).starts_with("run length"));
        assert!(rule(9, 4).starts_with("run length"));
        assert!(rule(9, 5).starts_with("the host"));
        assert!(rule(1, 1).starts_with("the host"));
        assert!(rule(30, 15).starts_with("run length"));
    }
}
