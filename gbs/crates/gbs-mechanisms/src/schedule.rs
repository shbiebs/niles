        let s = Schedule::new("q", 0, 360, 90, coupon(100)).unwrap();
        let occ = s.occurrences(&AllDays).unwrap();
        assert_eq!(occ[0].previous, None, "the first accrues from the effective date");
        assert_eq!(occ[0].accrual_days(0), 90);
        assert_eq!(occ[1].previous, Some(90));
        assert_eq!(occ[1].accrual_days(0), 90);
