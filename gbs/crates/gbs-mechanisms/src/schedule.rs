    #[test]
    fn a_contingency_that_does_not_fire_produces_nothing_rather_than_a_zero_posting() {
        // "Nothing happened" and "a zero-value thing happened" are different facts, and an
        // auditor will ask which. A cap below its strike did not pay; it did not pay zero.
        let s = Schedule::new("cap", 0, 360, 90, coupon(5_000))
            .unwrap()
            .contingent_on(Contingency::When(Box::new(|_occ, obs| {
                matches!(obs.get("SOFR"), Some((v, _)) if v > 50_000)
            })));

        let above = Observations::new().fix("SOFR", 60_000, 6);
        let below = Observations::new().fix("SOFR", 40_000, 6);

        assert_eq!(s.generate(&AllDays, 90, Epoch(1), &above).unwrap().len(), 1);
        assert!(
            s.generate(&AllDays, 90, Epoch(1), &below).unwrap().is_empty(),
            "below the strike, the cap produces no posting set at all"
        );
    }

    #[test]
    fn a_missing_fixing_is_absent_and_never_zero() {
        // The `Err(_) => 0` defect of §1.1.1, in the place it would cost most: an index that
        // did not fix must not be read as zero, or every cap pays out and every floor does
        // not.
        let obs = Observations::new().fix("SOFR", 52_500, 6);
        assert_eq!(obs.get("SOFR"), Some((52_500, 6)));
        assert_eq!(obs.get("ESTR"), None, "absent, not zero");
        assert!(!obs.has("ESTR"));

        // And a cap contingent on an absent index does not fire.
        let s = Schedule::new("cap", 0, 180, 90, coupon(1))
            .unwrap()
            .contingent_on(Contingency::When(Box::new(|_, obs| {
                matches!(obs.get("ESTR"), Some((v, _)) if v > 0)
            })));
        assert!(s.generate(&AllDays, 90, Epoch(1), &obs).unwrap().is_empty());
    }

    #[test]
    fn observations_are_passed_in_so_generation_is_reproducible() {
        // Determinism: the same observations give the same posting sets, forever. A
        // generator that read a live feed could not be reproduced at an epoch.
        let s = Schedule::new("q", 0, 90, 90, coupon(1_234)).unwrap();
        let obs = Observations::new().fix("SOFR", 52_500, 6);
        let first = s.generate(&AllDays, 90, Epoch(3), &obs).unwrap();
        for _ in 0..20 {
            assert_eq!(s.generate(&AllDays, 90, Epoch(3), &obs).unwrap(), first);
        }
    }

    #[test]
    fn a_generator_may_decline_and_that_is_not_an_empty_posting_set() {
        // A sweep already at target moves nothing. Returning an empty set would be refused
        // by the kernel as `Empty`; returning `None` is the two layers agreeing that no
        // movement is not a transaction.
        let declines: Generator = Box::new(|_, _| None);
        let s = Schedule::new("sweep", 0, 90, 30, declines).unwrap();
        assert!(s.generate(&AllDays, 30, Epoch(1), &Observations::new()).unwrap().is_empty());
        s.check_generator(&AllDays, &chart(), &[Observations::new()]).unwrap();
    }

    // ── amortisation ────────────────────────────────────────────────────────────────

    #[test]
    fn equal_instalments_sum_exactly_to_the_principal() {
        // $1,000.00 over 7 instalments: 100000/7 = 14285.71…, and the remainder must go
        // somewhere rather than evaporate.
        for (total, n) in [(100_000i128, 7u32), (100i128, 3), (1, 5), (0, 4), (999_999, 12)] {
            let parts = equal_instalments(&Amount::minor_2dp(total, "USD"), n);
            assert_eq!(parts.len(), n as usize);
            assert_eq!(parts.iter().map(|a| a.minor).sum::<i128>(), total, "total={total} n={n}");
        }
    }

    #[test]
    fn the_amortisation_remainder_lands_on_the_final_instalment() {
        // Where loan documents put it: the balancing payment is the last one.
        let parts = equal_instalments(&Amount::minor_2dp(100_000, "USD"), 7);
        assert_eq!(parts[0].minor, 14_285);
        assert_eq!(parts[6].minor, 14_290, "14285 + the 5-cent remainder");
    }

    #[test]
    fn a_negative_total_amortises_without_drifting() {
        // A refund schedule. `div_euclid` rather than `/` is what keeps this exact for
        // negatives — truncating division would round toward zero and leave a residue.
        let parts = equal_instalments(&Amount::minor_2dp(-100_000, "USD"), 7);
        assert_eq!(parts.iter().map(|a| a.minor).sum::<i128>(), -100_000);
    }

    #[test]
    fn zero_instalments_produces_nothing_rather_than_dividing_by_zero() {
        assert!(equal_instalments(&Amount::minor_2dp(100, "USD"), 0).is_empty());
    }
