    #[test]
    fn occurrences_are_computed_and_never_stored() {
        // Two calls must agree, and calling with a *different* calendar must give a
        // different answer — which is only possible if the list is derived.
        // Every 5 days from day 0: 5, 10, 15, 20, 25, 30. Under `Weekdays` (day 0 is a
        // Monday) days 5 and 20 fall on weekends and must roll — so the two calendars
        // genuinely disagree. An earlier version of this test used a 7-day period, where
        // every occurrence lands on a Monday and both calendars agree; it passed for the
        // wrong reason, which is worse than failing.
        let s = Schedule::new("q", 0, 30, 5, coupon(100)).unwrap();
        let a = s.occurrences(&AllDays).unwrap();
        let b = s.occurrences(&AllDays).unwrap();
        assert_eq!(a, b, "same calendar, same answer");

        let c = s.occurrences(&Weekdays).unwrap();
        assert_ne!(a, c, "the calendar changes the answer, so the list cannot be stored");
        assert_eq!(a.iter().map(|o| o.adjusted).collect::<Vec<_>>(), vec![5, 10, 15, 20, 25, 30]);
        assert_eq!(
            c.iter().map(|o| o.adjusted).collect::<Vec<_>>(),
            vec![7, 10, 15, 21, 25, 30],
            "day 5 (Sat) rolls to 7, day 20 (Sun) rolls to 21"
        );
    }

